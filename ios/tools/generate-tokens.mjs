// Generates the design-system token files from design/midad/tokens.json:
//   - colours: Assets.xcassets/Colors, and Tokens/MidadColor.swift
//   - the type scale: Tokens/MidadType.swift
//   - spacing, radii and sizes: Tokens/MidadMetrics.swift
//
// Run it again whenever tokens.json changes:
//
//   node ios/tools/generate-tokens.mjs
//
// It is not part of the Xcode build; the output is committed. TypeStyle.swift
// (which turns a style into a font) is hand-written and not generated.

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..');
const TOKENS = JSON.parse(readFileSync(join(REPO, 'design/midad/tokens.json'), 'utf8'));
const APP = join(REPO, 'ios/Awzan');
const ASSETS = join(APP, 'Resources/Assets.xcassets');
const OUT = join(APP, 'DesignSystem/Tokens');

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const px = (v) => Number(String(v).replace('px', ''));
const banner = (what) => `// GENERATED by ios/tools/generate-tokens.mjs from design/midad/tokens.json.
// ${what}
// Do not edit by hand — re-run the generator. Design system version ${TOKENS.version}.
`;

// ---------------------------------------------------------------- colours ---
// One colour set per token, holding both its Paper (light) and Night (dark)
// values, so a view that uses Midad.ink looks right in either theme.
function colorComponents(hex) {
  const h = hex.replace('#', '');
  const p = h.length === 3 ? h.split('').map((c) => c + c) : h.match(/../g);
  return {
    red: `0x${p[0].toUpperCase()}`,
    green: `0x${p[1].toUpperCase()}`,
    blue: `0x${p[2].toUpperCase()}`,
    alpha: p[3] ? (parseInt(p[3], 16) / 255).toFixed(3) : '1.000',
  };
}

function writeColors() {
  if (existsSync(join(ASSETS, 'Colors'))) rmSync(join(ASSETS, 'Colors'), { recursive: true });
  mkdirSync(join(ASSETS, 'Colors'), { recursive: true });
  writeFileSync(join(ASSETS, 'Contents.json'),
    JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n');
  writeFileSync(join(ASSETS, 'Colors/Contents.json'),
    JSON.stringify({ info: { author: 'xcode', version: 1 }, properties: { 'provides-namespace': false } }, null, 2) + '\n');

  const lines = [];
  for (const t of TOKENS.color.tokens) {
    const name = camel(t.name);
    const dir = join(ASSETS, 'Colors', `${name}.colorset`);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'Contents.json'), JSON.stringify({
      colors: [
        { color: { 'color-space': 'srgb', components: colorComponents(t.value.midad) }, idiom: 'universal' },
        {
          appearances: [{ appearance: 'luminosity', value: 'dark' }],
          color: { 'color-space': 'srgb', components: colorComponents(t.value['midad-night']) },
          idiom: 'universal',
        },
      ],
      info: { author: 'xcode', version: 1 },
    }, null, 2) + '\n');

    lines.push(`    /// ${t.usage}`);
    lines.push(`    ///`);
    lines.push(`    /// Paper \`${t.value.midad}\` · Night \`${t.value['midad-night']}\``);
    lines.push(`    public static let ${name} = Color(.${name})`);
    lines.push('');
  }

  const header = [
    banner('The twenty semantic colours, as one namespace over Assets.xcassets/Colors.'),
    'import SwiftUI',
    '',
    '/// The app\'s colours. Every colour comes from here (`Midad.ink`), and each has a',
    '/// Paper (light) and a Night (dark) value.',
    '///',
    '/// `sign` is only for the letters that carry the grammar, and `correct` and',
    '/// `wrong` only colour answer options. They are never mixed.',
    '///',
    '/// This is a namespace rather than an extension of `Color`, because names like',
    '/// `fill` and `line` already exist in SwiftUI.',
    'public enum Midad {',
    '',
  ].join('\n');
  writeFileSync(join(OUT, 'MidadColor.swift'), header + lines.join('\n') + '}\n');
  return TOKENS.color.tokens.length;
}

// ------------------------------------------------------------------- type ---
// Which Dynamic Type category each style scales with. tokens.json doesn't say,
// so it is chosen here.
const RAMP = {
  'arabic-hero': 'largeTitle', 'arabic-display': 'title', 'arabic-title': 'title2',
  'arabic-cell': 'title3', 'arabic-body': 'body', 'arabic-label': 'subheadline',
  'screen-title': 'largeTitle', 'meaning-display': 'title2', 'reading': 'subheadline',
  'gloss': 'callout',
  'headline': 'headline', 'verdict': 'title3', 'body': 'body', 'label': 'footnote',
  'caption': 'caption', 'numeral': 'title',
};

const FACE_BLURB = {
  arabic: 'Scheherazade New. Used for every Arabic word the app teaches.',
  serif: 'Newsreader. Used for meanings: glosses and English readings.',
  sans: 'The system font. Used for interface text.',
};

function writeType() {
  const out = [];
  let count = 0;
  for (const group of TOKENS.type.groups) {
    out.push(`    // MARK: - ${group.name}`);
    out.push(`    //`);
    out.push(`    // ${FACE_BLURB[group.family]}`);
    out.push('');
    for (const s of group.styles) {
      const name = camel(s.name);
      const ramp = RAMP[s.name];
      if (!ramp) throw new Error(`no Dynamic Type ramp declared for "${s.name}"`);
      out.push(`    /// ${s.usage}`);
      out.push(`    ///`);
      out.push(`    /// \`${px(s.fontSize)} / ${px(s.lineHeight)}\`${s.fontWeight !== 400 ? `, weight ${s.fontWeight}` : ''}${s.fontStyle === 'italic' ? ', italic' : ''} — e.g. ${s.sample}`);
      out.push(`    static let ${name} = TypeStyle(`);
      out.push(`        face: .${group.family},`);
      out.push(`        size: ${px(s.fontSize)},`);
      out.push(`        lineHeight: ${px(s.lineHeight)},`);
      out.push(`        weight: ${s.fontWeight},`);
      out.push(`        italic: ${s.fontStyle === 'italic'},`);
      out.push(`        tracking: ${s.letterSpacing ? Number(String(s.letterSpacing).replace('em', '')) : 0},`);
      out.push(`        ramp: .${ramp}${s.name === 'numeral' ? ',\n        tabularFigures: true' : ''}`);
      out.push(`    )`);
      out.push('');
      count++;
    }
  }
  const header = [
    banner('The type scale. TypeStyle itself — how a style becomes a font — is hand-written next door.'),
    'import SwiftUI',
    '',
    '/// The type scale, in three faces: Arabic for the words being studied, an italic',
    '/// serif for meanings, and the system sans for the interface.',
    '///',
    '/// Each style has its own line height, because vowelled Arabic is taller than a',
    "/// font's normal line. See `TypeStyle`.",
    'public extension TypeStyle {',
    '',
  ].join('\n');
  writeFileSync(join(OUT, 'MidadType.swift'), header + out.join('\n') + '}\n');
  return count;
}

// ---------------------------------------------------------------- metrics ---
function writeMetrics() {
  const section = (title, note, tokens, kind) => {
    const rows = [];
    rows.push(`    // MARK: - ${title}`);
    rows.push(`    //`);
    for (const line of note.match(/.{1,74}(\s|$)/g)) rows.push(`    // ${line.trim()}`);
    rows.push('');
    for (const t of tokens) {
      const name = camel(t.name.replace(/^(space|radius)-/, ''));
      rows.push(`    /// ${t.usage}`);
      // No prefix for the fixed sizes: it's `tapTarget`, not `sizeTapTarget`.
      const swift = kind ? `${kind}${name[0].toUpperCase()}${name.slice(1)}` : name;
      rows.push(`    static let ${swift}: CGFloat = ${px(t.value)}`);
      rows.push('');
    }
    return rows.join('\n');
  };

  const header = [
    banner('Spacing, corner radii and the fixed sizes.'),
    'import CoreGraphics',
    '',
    '/// Spacing (on a 4pt base), corner radii and the fixed sizes.',
    '///',
    '/// There is no `radiusFull`: use `Capsule()` for a fully rounded shape.',
    'public extension Midad {',
    '',
  ].join('\n');
  writeFileSync(join(OUT, 'MidadMetrics.swift'), header
    + section('Spacing', TOKENS.spacing.note, TOKENS.spacing.tokens, 'space') + '\n'
    + section('Radii', TOKENS.radius.note, TOKENS.radius.tokens.filter((t) => t.name !== 'radius-full'), 'radius') + '\n'
    + section('Fixed sizes', TOKENS.size.note, TOKENS.size.tokens, '') + '}\n');
  return TOKENS.spacing.tokens.length + TOKENS.radius.tokens.length - 1 + TOKENS.size.tokens.length;
}

mkdirSync(OUT, { recursive: true });
console.log(`colours   ${writeColors()}`);
console.log(`type      ${writeType()}`);
console.log(`metrics   ${writeMetrics()}`);
